const seen = new Set<string>();
for (const group of FINANCE_TITLE_GROUPS) {
  for (const title of group.titles) {
    if (seen.has(title)) throw new Error(`Duplicate finance title: ${title}`);
    seen.add(title);
  }
}

export const FINANCE_TITLES: ReadonlySet<string> = seen;

export function titleLockedUntil(changedAt: Date | null | undefined): Date | null {
  if (!changedAt) return null;
  const until = new Date(changedAt.getTime() + TITLE_LOCK_MS);
  return until.getTime() > Date.now() ? until : null;
}
